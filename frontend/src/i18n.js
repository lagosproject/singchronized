export function t(key, params = {}) {
  const langObj = translations[currentLang] || translations['en'];
  let val = langObj[key];
  if (val === undefined) {
    val = translations['en'][key] || key;
  }
  
  if (typeof params.count === 'number') {
    const suffix = params.count === 1 ? '_singular' : '_plural';
    const countKey = `${key}${suffix}`;
    if (langObj[countKey] !== undefined) {
      val = langObj[countKey];
    } else if (translations['en'][countKey] !== undefined) {
      val = translations['en'][countKey];
    }
  }

  Object.keys(params).forEach(paramKey => {
    val = val.replaceAll(`{${paramKey}}`, params[paramKey]);
  });
  return val;
}
